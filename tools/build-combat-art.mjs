#!/usr/bin/env node
// Derives bounded full-figure crops and boot pivots from preserved transparent PNGs.
import sharp from 'sharp';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
const manifest=JSON.parse(await readFile(new URL('tools/combat-art-sources.json',root),'utf8'));
async function output(url,bytes){if(check){const old=await readFile(url);if(!old.equals(Buffer.from(bytes)))throw new Error('Combat art out of date: '+url.pathname);}else await writeFile(url,bytes);}
const definitions=[],actors={};
for(const source of manifest.sources){
 const input=await readFile(new URL('tanahoraflavio/assets/'+source.file+'.png',root));
 const {data,info:{width,height,channels}}=await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const seen=new Uint8Array(width*height),figures=[];
 for(let start=0;start<width*height;start++){
  if(seen[start]||data[start*channels+3]<=64)continue;
  const stack=[start];seen[start]=1;let area=0,x0=width,y0=height,x1=0,y1=0;
  while(stack.length){const pixel=stack.pop(),x=pixel%width,y=Math.floor(pixel/width);area++;
   x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);
   for(const next of [pixel-1,pixel+1,pixel-width,pixel+width])if(next>=0&&next<width*height&&!seen[next]&&Math.abs(next%width-x)<=1&&data[next*channels+3]>64){seen[next]=1;stack.push(next);}
  }
  if(area>2000)figures.push({x0,y0,x1,y1});
 }
 if(figures.length!==16)throw new Error('Expected 16 separate complete figures: '+source.name);
 const frames=[];
 for(let row=0;row<4;row++)for(let col=0;col<4;col++){
  // Hands can extend past nominal cell borders. Connected silhouettes prevent
  // chopping fingers or accidentally sampling a piece of the NEXT character.
  const figure=figures.find(f=>Math.floor((f.x0+f.x1)/2/(width/4))===col&&Math.floor((f.y0+f.y1)/2/(height/4))===row);
  if(!figure)throw new Error('Missing figure '+row+'/'+col);
  const {x0,y0,x1,y1}=figure,left=Math.floor(col*width/4),top=Math.floor(row*height/4);
  let footLeft=width,footRight=0;
  for(let y=y1-Math.round((y1-y0)*.09);y<=y1;y++)for(let x=x0;x<=x1;x++)if(data[(y*width+x)*channels+3]>128){footLeft=Math.min(footLeft,x);footRight=Math.max(footRight,x);}
  // Points reviewed on the full-size grid: palm, phone, and ghost hat tip.
  const type=source.actors[row],u=type.startsWith('flavio')?.88:type==='meme-army'?(col===2?.06:.15):col===2?.105:.28;
  const v=type==='flavio-slide-shot'?.60:type.startsWith('flavio')?.405:type==='meme-army'?.33:col===2?.55:.65;
  frames.push({x:x0-2,y:y0-2,width:x1-x0+5,height:y1-y0+5,center:(footLeft+footRight)/2,groundY:y1+1,muzzle:{x:Math.round(left+width/4*u),y:Math.round(top+height/4*v)}});
 }
 for(let row=0;row<4;row++)if(source.actors[row].endsWith('-run')||source.actors[row]==='flavio-air-shot'){const groundY=Math.max(...frames.slice(row*4,row*4+4).map(f=>f.groundY));for(const f of frames.slice(row*4,row*4+4))f.groundY=groundY;}
 const webp=await sharp(input).webp({lossless:true,effort:6}).toBuffer(),sha256=createHash('sha256').update(webp).digest('hex');
 await output(new URL('tanahoraflavio/assets/'+source.file+'.webp',root),webp);
 definitions.push(`${source.name}:{url:new URL('./assets/${source.file}.webp',import.meta.url).href+'?v=${sha256.slice(0,12)}',width:${width},height:${height},sha256:'${sha256}',frames:${JSON.stringify(frames)}}`);
 source.actors.forEach((type,row)=>{actors[type]={sheet:source.name,row,facing:type.startsWith('flavio')?1:-1};});
 console.log(source.name,webp.length,'bytes, 16 complete frames');
}
await output(new URL('tanahoraflavio/runner-combat-sprite-data.mjs',root),`// Generated by tools/build-combat-art.mjs; full illustrated figures, never head crops.\nexport const combatActors=${JSON.stringify(actors,null,2)};\nexport const combatDefinitions={${definitions.join(',\n')}};\n`);
