#!/usr/bin/env node
// Measure complete poses; retain the image_gen source PNG and every source alpha.
import sharp from 'sharp';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
const {sources}=JSON.parse(await readFile(new URL('tools/signature-art-sources.json',root),'utf8'));
const definitions={},props={};
for(const source of sources){
 const input=await readFile(new URL(`tanahoraflavio/assets/${source.file}.png`,root));
 const {data,info:{width,height,channels}}=await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const frames=[];
 for(let row=0;row<4;row++){
  const poses=[];
  for(let col=0;col<4;col++){
   const left=Math.floor(col*width/4),right=Math.floor((col+1)*width/4),top=Math.floor(row*height/4),bottom=Math.floor((row+1)*height/4);
   let x0=right,y0=bottom,x1=-1,y1=-1;
   // image_gen includes near-invisible alpha=1 RGB noise in transparent gutters.
   // Measure the drawn body, retaining its antialiased edge with the padding.
   // The original alpha for the entire sheet is still encoded unchanged.
   for(let y=top;y<bottom;y++)for(let x=left;x<right;x++)if(data[(y*width+x)*channels+3]>64){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}
   if(x1<x0||y1<y0)throw new Error('Missing complete signature pose '+source.name+'/'+row+'/'+col);
   // Transparent padding is bounded by the cell, never clips another drawing.
   const x=Math.max(left,x0-2),y=Math.max(top,y0-2),w=Math.min(right,x1+3)-x,h=Math.min(bottom,y1+3)-y;
   poses.push({x,y,width:w,height:h,centerX:x+w/2,centerY:y+h/2});
  }
  props[source.types[row]]={sheet:source.name,start:frames.length,width:Math.max(...poses.map(p=>p.width)),height:Math.max(...poses.map(p=>p.height))};
  frames.push(...poses);
 }
 const webp=await sharp(input).webp({lossless:true,effort:6}).toBuffer(),sha256=createHash('sha256').update(webp).digest('hex');
 definitions[source.name]={url:`./assets/${source.file}.webp`,width,height,sha256,frames};
 const path=new URL(`tanahoraflavio/assets/${source.file}.webp`,root);
 if(check){if(!(await readFile(path)).equals(webp))throw new Error('Signature WebP out of date: '+source.file);}else await writeFile(path,webp);
 console.log(source.name,webp.length,'bytes, 16 complete poses; source alpha unchanged');
}
const entries=Object.entries(definitions).map(([name,d])=>`${name}:{...${JSON.stringify(d)},url:new URL('${d.url}',import.meta.url).href+'?v=${d.sha256.slice(0,12)}'}`).join(',\n');
const module=Buffer.from(`// Generated by tools/build-signature-art.mjs; sources/provenance in tools/signature-art-sources.json.\nexport const signatureDefinitions={${entries}};\nexport const signatureProps=${JSON.stringify(props)};\n`);
const path=new URL('tanahoraflavio/runner-signature-sprite-data.mjs',root);
if(check){if(!(await readFile(path)).equals(module))throw new Error('Signature manifest out of date');}else await writeFile(path,module);
