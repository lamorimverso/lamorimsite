#!/usr/bin/env node
// Preserve the image_gen PNG and its native alpha; only encode and measure it.
import sharp from 'sharp';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
const source=JSON.parse(await readFile(new URL('tanahoraflavio/assets/flavio-crouch-v1.source.json',root),'utf8'));
const input=await readFile(new URL('tanahoraflavio/assets/flavio-crouch-v1.png',root));
const {data,info:{width,height,channels}}=await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const frames=[];
for(let row=0;row<2;row++)for(let col=0;col<4;col++){
 let x0=width,y0=height,x1=-1,y1=-1;
 for(let y=Math.floor(row*height/2);y<Math.floor((row+1)*height/2);y++)for(let x=Math.floor(col*width/4);x<Math.floor((col+1)*width/4);x++){
  if(data[(y*width+x)*channels+3]<=64)continue;
  x0=Math.min(x0,x);y0=Math.min(y0,y);x1=Math.max(x1,x);y1=Math.max(y1,y);
 }
 if(x1<x0||y1<y0)throw new Error('Missing complete crouch figure '+row+'/'+col);
 let footLeft=width,footRight=-1;
 for(let y=y1-Math.round((y1-y0)*.09);y<=y1;y++)for(let x=x0;x<=x1;x++)if(data[(y*width+x)*channels+3]>128){footLeft=Math.min(footLeft,x);footRight=Math.max(footRight,x);}
 let muzzle=null;
 if(row===1){
  // Reviewed purple barrel: its last coloured column ends just inside the ink.
  let tip=-1,ys=[];
  for(let x=Math.ceil(x0+(x1-x0)*.72);x<=x1;x++)for(let y=y0;y<=y0+(y1-y0)*.72;y++){
   const i=(Math.floor(y)*width+x)*channels,r=data[i],g=data[i+1],b=data[i+2];
   if(data[i+3]>128&&r>45&&b>r*1.04&&b>g*1.15){if(x>tip){tip=x;ys=[];}if(x===tip)ys.push(y);}
  }
  if(tip<0||!ys.length)throw new Error('Missing complete IVER barrel '+col);
  muzzle={x:Math.min(x1,tip+2),y:Math.round((Math.min(...ys)+Math.max(...ys))/2)};
 }
 frames.push({x:x0-2,y:y0-2,width:x1-x0+5,height:y1-y0+5,center:(footLeft+footRight)/2,groundY:y1+1,neck:source.neckAnchors[row*4+col],muzzle});
}
const webp=await sharp(input).webp({lossless:true,effort:6}).toBuffer(),sha256=createHash('sha256').update(webp).digest('hex');
const module=`// Generated by tools/build-crouch-art.mjs from the preserved image_gen PNG.\nexport const crouchDefinition={url:new URL('./assets/flavio-crouch-v1.webp',import.meta.url).href+'?v=${sha256.slice(0,12)}',width:${width},height:${height},sha256:'${sha256}',frames:${JSON.stringify(frames)}};\n`;
for(const [file,bytes] of [['tanahoraflavio/assets/flavio-crouch-v1.webp',webp],['tanahoraflavio/runner-crouch-sprite-data.mjs',Buffer.from(module)]]){
 const url=new URL(file,root);
 if(check){if(!(await readFile(url)).equals(bytes))throw new Error('Crouch artwork out of date: '+file);}
 else await writeFile(url,bytes);
}
console.log('heroCrouch',webp.length,'bytes, 8 complete frames; original PNG/alpha unchanged');
