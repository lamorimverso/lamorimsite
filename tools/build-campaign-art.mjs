// Packs complete generated figures. It never redraws or assembles body parts.
import sharp from 'sharp';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
const sources=[
 {name:'campaignA',file:'campaign-illustrated-a-v1',actors:['ana-elisa','rick','guilherme','erika']},
 {name:'campaignB',file:'campaign-illustrated-b-v1',actors:['fiscal','renato-freitas','jones','maestro']},
 {name:'campaignC',file:'campaign-illustrated-c-v1',actors:['sofia','capita','povo']}
];
async function output(path,bytes){
 const url=new URL(path,root);
 if(check){if(!(await readFile(url)).equals(Buffer.from(bytes)))throw Error('Campaign art out of date: '+path);}
 else await writeFile(url,bytes);
}
const definitions=[],actors={};
for(const source of sources){
 const input=await readFile(new URL('tanahoraflavio/assets/'+source.file+'.png',root));
 const {data,info:{width,height}}=await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const seen=new Uint8Array(width*height),parts=[];
 for(let start=0;start<width*height;start++){
  if(seen[start]||data[start*4+3]<=64)continue;
  const stack=[start];seen[start]=1;let area=0,x0=width,y0=height,x1=0,y1=0;
  while(stack.length){
   const pixel=stack.pop(),x=pixel%width,y=Math.floor(pixel/width);area++;
   x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);
   for(const next of [pixel-1,pixel+1,pixel-width,pixel+width])if(next>=0&&next<width*height&&!seen[next]&&Math.abs(next%width-x)<=1&&data[next*4+3]>64){seen[next]=1;stack.push(next);}
  }
  if(area>60)parts.push({x0,y0,x1,y1,area});
 }
 const frames=[];
 for(let row=0;row<source.actors.length;row++)for(let col=0;col<4;col++){
  const figures=parts.filter(f=>Math.floor((f.x0+f.x1)/2/(width/4))===col&&Math.floor((f.y0+f.y1)/2/(height/source.actors.length))===row);
  if(!figures.length)throw Error('Missing complete figure '+source.name+'/'+row+'/'+col);
  const x0=Math.min(...figures.map(f=>f.x0)),x1=Math.max(...figures.map(f=>f.x1)),y0=Math.min(...figures.map(f=>f.y0)),y1=Math.max(...figures.map(f=>f.y1));
  let footLeft=width,footRight=0;
  for(let y=y1-Math.round((y1-y0)*.08);y<=y1;y++)for(let x=x0;x<=x1;x++)if(data[(y*width+x)*4+3]>128){footLeft=Math.min(footLeft,x);footRight=Math.max(footRight,x);}
  frames.push({x:Math.max(0,x0-2),y:Math.max(0,y0-2),width:Math.min(width-1,x1+2)-Math.max(0,x0-2)+1,height:Math.min(height-1,y1+2)-Math.max(0,y0-2)+1,center:(footLeft+footRight)/2,groundY:y1+1});
 }
 for(const [row,type] of source.actors.entries()){
  const group=frames.slice(row*4,row*4+4),neutral=group[0];
  actors[type]={sheet:source.name,row,height:Math.max(...group.map(f=>f.groundY-f.y)),logicalHeight:type==='povo'?105:110};
  // Portraits use the same neutral illustration as the complete character.
  const headHeight=Math.round(neutral.height*.52),headWidth=type==='povo'?neutral.width:Math.min(neutral.width,Math.round(headHeight*1.12));
  actors[type].portrait={x:type==='povo'?neutral.x:Math.round(neutral.center-headWidth*.52),y:neutral.y,width:headWidth,height:type==='povo'?neutral.height:headHeight};
 }
 const bytes=await sharp(input).webp({lossless:true,effort:6}).toBuffer(),sha256=createHash('sha256').update(bytes).digest('hex');
 await output('tanahoraflavio/assets/'+source.file+'.webp',bytes);
 definitions.push(`${source.name}:{url:new URL('./assets/${source.file}.webp',import.meta.url).href+'?v=${sha256.slice(0,12)}',width:${width},height:${height},sha256:'${sha256}',frames:${JSON.stringify(frames)}}`);
 console.log(source.name,frames.length,'complete poses,',bytes.length,'bytes');
}
await output('tanahoraflavio/runner-campaign-sprite-data.mjs',`// Generated by tools/build-campaign-art.mjs. Complete illustrated figures.\nexport const campaignActors=${JSON.stringify(actors,null,2)};\nexport const campaignDefinitions={${definitions.join(',\n')}};\n`);
